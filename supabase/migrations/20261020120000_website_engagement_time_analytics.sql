-- Measure engaged time with explicit, bounded client heartbeats.
-- Detailed telemetry is private and automatically expires after 30 days; lifetime visits are untouched.
CREATE TABLE IF NOT EXISTS public.website_engagement_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id uuid NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  session_id uuid NOT NULL,
  visitor_id uuid NOT NULL,
  page_path text NOT NULL DEFAULT '/',
  engaged_seconds smallint NOT NULL CHECK (engaged_seconds BETWEEN 1 AND 15)
);

CREATE INDEX IF NOT EXISTS website_engagement_events_created_at_idx
  ON public.website_engagement_events (created_at DESC);
CREATE INDEX IF NOT EXISTS website_engagement_events_session_created_idx
  ON public.website_engagement_events (session_id, created_at DESC);
CREATE INDEX IF NOT EXISTS website_engagement_events_page_created_idx
  ON public.website_engagement_events (page_path, created_at DESC);

ALTER TABLE public.website_engagement_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.website_engagement_events FROM anon, authenticated, PUBLIC;
GRANT ALL ON TABLE public.website_engagement_events TO service_role;

CREATE OR REPLACE FUNCTION public.get_website_engagement_stats(p_timeframe text DEFAULT '24h')
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_duration interval;
  v_start timestamptz;
  v_total_seconds bigint := 0;
  v_sessions bigint := 0;
  v_average numeric := NULL;
  v_average_page numeric := NULL;
BEGIN
  IF lower(coalesce(p_timeframe, '24h')) = '7d' THEN
    v_duration := interval '7 days';
  ELSIF lower(coalesce(p_timeframe, '24h')) = '30d' THEN
    v_duration := interval '30 days';
  ELSE
    v_duration := interval '24 hours';
  END IF;
  v_start := now() - v_duration;

  SELECT coalesce(sum(engaged_seconds), 0), count(DISTINCT session_id)
    INTO v_total_seconds, v_sessions
  FROM public.website_engagement_events
  WHERE created_at >= v_start AND created_at <= now();

  IF v_sessions > 0 THEN
    v_average := round(v_total_seconds::numeric / v_sessions, 1);
  END IF;

  SELECT round(avg(page_seconds)::numeric, 1)
    INTO v_average_page
  FROM (
    SELECT session_id, page_path, sum(engaged_seconds)::numeric AS page_seconds
    FROM public.website_engagement_events
    WHERE created_at >= v_start AND created_at <= now()
    GROUP BY session_id, page_path
  ) page_totals;

  RETURN jsonb_build_object(
    'status', CASE WHEN v_sessions > 0 THEN 'available' ELSE 'not_tracked_yet' END,
    'definition', 'Sum of visible-tab engagement heartbeats after recent user interaction; hidden and idle time excluded; maximum 15 seconds per sample.',
    'engaged_seconds', v_total_seconds,
    'measured_sessions', v_sessions,
    'average_seconds_per_session', v_average,
    'average_seconds_per_page', v_average_page,
    'sample_count', (SELECT count(*) FROM public.website_engagement_events WHERE created_at >= v_start AND created_at <= now()),
    'retention_days', 30
  );
END;
$$;

REVOKE ALL ON FUNCTION public.get_website_engagement_stats(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.get_website_engagement_stats(text) TO anon, authenticated, service_role;

-- Use a single named daily cleanup job; do not create duplicate schedules on re-apply.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM cron.job WHERE jobname = 'purge-website-engagement-events-30d') THEN
    PERFORM cron.schedule(
      'purge-website-engagement-events-30d',
      '17 3 * * *',
      $job$DELETE FROM public.website_engagement_events WHERE created_at < now() - interval '30 days';$job$
    );
  END IF;
END;
$$;

NOTIFY pgrst, 'reload schema';
