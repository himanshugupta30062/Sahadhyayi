-- Expire old records hourly. Every analytics read is also bounded to the selected period (maximum 30 days).
DELETE FROM public.website_action_events
WHERE visited_at < now() - interval '30 days';

DO $retention_job$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM cron.job WHERE jobname = 'website-action-events-retention'
  ) THEN
    PERFORM cron.schedule(
      'website-action-events-retention',
      '17 * * * *',
      $command$DELETE FROM public.website_action_events WHERE visited_at < now() - interval '30 days';$command$
    );
  END IF;
END;
