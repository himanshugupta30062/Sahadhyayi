-- Short-lived detailed web analytics. The original website_visits table remains the historical source
-- for lifetime/universal visit counters. All new detailed pageviews and UI/product events go here.
CREATE EXTENSION IF NOT EXISTS pg_cron WITH SCHEMA pg_catalog;

CREATE TABLE IF NOT EXISTS public.website_action_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id uuid NOT NULL DEFAULT gen_random_uuid(),
  visited_at timestamptz NOT NULL DEFAULT now(),
  event_type text NOT NULL,
  event_name text,
  visitor_id uuid,
  session_id uuid,
  user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  page_url text NOT NULL DEFAULT '/',
  referrer text,
  country_code text,
  city text,
  region text,
  browser text,
  browser_version text,
  os text,
  device_type text,
  device_model text,
  screen_resolution text,
  language text,
  timezone text,
  utm_source text,
  utm_medium text,
  utm_campaign text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  CONSTRAINT website_action_events_event_type_check
    CHECK (event_type IN ('pageview', 'activity')),
  CONSTRAINT website_action_events_activity_name_check
    CHECK (event_type = 'pageview' OR nullif(btrim(event_name), '') IS NOT NULL),
  CONSTRAINT website_action_events_event_name_format_check
    CHECK (event_name IS NULL OR event_name ~ '^[a-z][a-z0-9_.-]{0,79}$')
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_website_action_events_event_id
  ON public.website_action_events(event_id);
CREATE INDEX IF NOT EXISTS idx_website_action_events_type_time
  ON public.website_action_events(event_type, visited_at DESC);
CREATE INDEX IF NOT EXISTS idx_website_action_events_name_time
  ON public.website_action_events(event_name, visited_at DESC)
  WHERE event_name IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_website_action_events_session_time
  ON public.website_action_events(session_id, visited_at DESC)
  WHERE session_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_website_action_events_visitor_time
  ON public.website_action_events(visitor_id, visited_at DESC)
  WHERE visitor_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_website_action_events_city_time
  ON public.website_action_events(city, visited_at DESC)
  WHERE city IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_website_action_events_time
  ON public.website_action_events(visited_at DESC);

ALTER TABLE public.website_action_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.website_action_events FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE public.website_action_events TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.website_action_events_id_seq TO service_role;

