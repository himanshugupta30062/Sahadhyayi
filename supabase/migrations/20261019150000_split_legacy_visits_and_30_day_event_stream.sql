-- Lifetime stats continue to use website_visits. Period traffic, geography, devices, and pages use the new event stream.
CREATE OR REPLACE FUNCTION public.get_community_pulse_stats(
  p_timeframe text DEFAULT '24h'
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_timeframe text := lower(coalesce(p_timeframe, '24h'));
  v_period_start timestamptz;
  v_total_signups bigint := 0;
  v_new_signups bigint := 0;
  v_total_visits bigint := 0;
  v_period_visits bigint := 0;
  v_unique_visitors bigint := NULL;
  v_hourly jsonb := '[]'::jsonb;
  v_countries jsonb := '[]'::jsonb;
  v_pages jsonb := '[]'::jsonb;
  v_devices jsonb := '[]'::jsonb;
  v_referrers jsonb := '[]'::jsonb;
  v_reading_engagement jsonb := '{}'::jsonb;
  v_now timestamptz := now();
BEGIN
  IF v_timeframe NOT IN ('24h', '7d', '30d') THEN
    v_timeframe := '24h';
  END IF;

  v_period_start := v_now - CASE v_timeframe
    WHEN '7d' THEN interval '7 days'
    WHEN '30d' THEN interval '30 days'
    ELSE interval '24 hours'
  END;

  SELECT count(*) INTO v_total_signups FROM public.profiles;
  SELECT count(*) INTO v_new_signups FROM public.profiles WHERE created_at >= v_period_start;
  SELECT count(*) INTO v_total_visits FROM public.website_visits WHERE event_type = 'pageview';
  SELECT count(*) INTO v_period_visits
  FROM public.website_action_events
  WHERE visited_at >= v_period_start AND event_type = 'pageview';

  SELECT CASE
    WHEN count(*) FILTER (WHERE visitor_id IS NOT NULL OR session_id IS NOT NULL) = 0
      THEN NULL::bigint
    ELSE count(DISTINCT coalesce(visitor_id::text, session_id::text))
  END
  INTO v_unique_visitors
  FROM public.website_action_events
  WHERE visited_at >= v_period_start
    AND event_type = 'pageview';

  WITH hours AS (
    SELECT generate_series(0, 23) AS idx
  ), buckets AS (
    SELECT h.idx,
      to_char((v_now AT TIME ZONE 'Asia/Kolkata') - (23 - h.idx) * interval '1 hour', 'FMHH12 AM') AS label,
      count(w.id)::bigint AS amount
    FROM hours h
    LEFT JOIN public.website_action_events w
      ON w.visited_at >= v_now - (24 - h.idx) * interval '1 hour'
     AND w.visited_at < v_now - (23 - h.idx) * interval '1 hour'
     AND w.event_type = 'pageview'
    GROUP BY h.idx
  )
  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'hourIndex', idx, 'label', label, 'count', amount,
    'isPeak', amount > 0 AND amount = (SELECT max(amount) FROM buckets)
  ) ORDER BY idx), '[]'::jsonb)
  INTO v_hourly FROM buckets;

  SELECT coalesce(jsonb_agg(jsonb_build_object('name', name, 'code', code, 'count', amount,
    'percent', CASE WHEN v_period_visits > 0 THEN round(amount * 100.0 / v_period_visits)::integer ELSE 0 END)
    ORDER BY amount DESC), '[]'::jsonb)
  INTO v_countries
  FROM (
    SELECT coalesce(nullif(country_code, ''), 'Unknown') AS name,
      nullif(country_code, '') AS code, count(*)::bigint AS amount
    FROM public.website_action_events
    WHERE visited_at >= v_period_start AND event_type = 'pageview'
    GROUP BY 1, 2 ORDER BY amount DESC LIMIT 5
  ) country_rows;

  SELECT coalesce(jsonb_agg(jsonb_build_object('name', name, 'count', amount,
    'percent', CASE WHEN v_period_visits > 0 THEN round(amount * 100.0 / v_period_visits)::integer ELSE 0 END)
    ORDER BY amount DESC), '[]'::jsonb)
  INTO v_pages
  FROM (
    SELECT coalesce(nullif(split_part(split_part(page_url, '?', 1), '#', 1), ''), '/') AS name,
      count(*)::bigint AS amount
    FROM public.website_action_events
    WHERE visited_at >= v_period_start AND event_type = 'pageview'
    GROUP BY 1 ORDER BY amount DESC LIMIT 5
  ) page_rows;

  SELECT coalesce(jsonb_agg(jsonb_build_object('name', name, 'count', amount,
    'percent', CASE WHEN v_period_visits > 0 THEN round(amount * 100.0 / v_period_visits)::integer ELSE 0 END)
    ORDER BY amount DESC), '[]'::jsonb)
  INTO v_devices
  FROM (
    SELECT coalesce(nullif(device_type, ''), 'Unknown') AS name, count(*)::bigint AS amount
    FROM public.website_action_events
    WHERE visited_at >= v_period_start AND event_type = 'pageview'
    GROUP BY 1 ORDER BY amount DESC LIMIT 4
  ) device_rows;

  SELECT coalesce(jsonb_agg(jsonb_build_object('name', name, 'count', amount,
    'percent', CASE WHEN v_period_visits > 0 THEN round(amount * 100.0 / v_period_visits)::integer ELSE 0 END)
    ORDER BY amount DESC), '[]'::jsonb)
  INTO v_referrers
  FROM (
    SELECT coalesce(nullif(split_part(split_part(referrer, '/', 3), ':', 1), ''), 'Direct') AS name,
      count(*)::bigint AS amount
    FROM public.website_action_events
    WHERE visited_at >= v_period_start AND event_type = 'pageview'
    GROUP BY 1 ORDER BY amount DESC LIMIT 5
  ) referrer_rows;

  SELECT jsonb_build_object(
    'bookViews', (
      SELECT count(*) FROM public.website_action_events
      WHERE visited_at >= v_period_start AND event_type = 'activity' AND event_name IN ('book_opened', 'discovery_book_opened')
    ),
    'readingProgressUpdates', (
      SELECT count(*) FROM public.reading_room_events
      WHERE created_at >= v_period_start AND kind = 'chapter_complete'
    ),
    'groupJoins', (
      SELECT count(*) FROM public.group_members WHERE joined_at >= v_period_start
    ),
    'discussions', (
      SELECT count(*) FROM public.posts WHERE created_at >= v_period_start
    ) + (
      SELECT count(*) FROM public.post_comments WHERE created_at >= v_period_start
    )
  ) INTO v_reading_engagement;

  RETURN jsonb_build_object(
    'timeframe', v_timeframe,
    'totalSignups', v_total_signups,
    'newSignups24h', v_new_signups,
    'totalVisits', v_total_visits,
    'lifetimeVisits', v_total_visits,
    'periodPageViews', v_period_visits,
    'analyticsRetentionDays', 30,
    'last24hVisits', v_period_visits,
    'uniqueVisitors24h', v_unique_visitors,
    'avgTimeOnSite', '—',
    'hourlyActivity', v_hourly,
    'topCountries', v_countries,
    'topPages', v_pages,
    'devices', v_devices,
    'referrers', v_referrers,
    'readingEngagement', v_reading_engagement,
    'lastUpdated', to_char(v_now AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
  );
END;
$function$;

COMMENT ON FUNCTION public.get_community_pulse_stats(text) IS
  'Lifetime visit total is sourced from legacy website_visits. Selected-period pageviews, unique visitors and traffic breakdowns are sourced from website_action_events (30-day retention).';

-- Every action metric is sourced only from the new, rolling 30-day event table.
CREATE OR REPLACE FUNCTION public.get_community_pulse_action_stats(
  p_timeframe text DEFAULT '24h'
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY INVOKER
SET search_path = public, pg_temp
AS $function$
DECLARE
  v_timeframe text := lower(coalesce(p_timeframe, '24h'));
  v_now timestamptz := now();
  v_period_start timestamptz;
  v_total_actions bigint := 0;
  v_total_interactions bigint := 0;
  v_active_sessions bigint := 0;
  v_average_session_duration_seconds integer := NULL;
  v_duration_sample_count bigint := 0;
  v_action_summary jsonb := '[]'::jsonb;
  v_scroll_depth_summary jsonb := '[]'::jsonb;
BEGIN
  IF v_timeframe NOT IN ('24h', '7d', '30d') THEN
    v_timeframe := '24h';
  END IF;

  v_period_start := v_now - CASE v_timeframe
    WHEN '7d' THEN interval '7 days'
    WHEN '30d' THEN interval '30 days'
    ELSE interval '24 hours'
  END;

  -- Explicit product events, excluding generic DOM interactions and telemetry events.
  SELECT count(*)::bigint
  INTO v_total_actions
  FROM public.website_action_events
  WHERE event_type = 'activity'
    AND event_name IS NOT NULL
    AND event_name NOT IN (
      'page_engagement_duration', 'scroll_depth',
      'navigation_click', 'ui_click', 'control_changed', 'form_submitted'
    )
    AND visited_at >= v_period_start
    AND visited_at <= v_now;

  -- Broad click/navigation/control/form interaction telemetry, shown separately from product events.
  SELECT count(*)::bigint
  INTO v_total_interactions
  FROM public.website_action_events
  WHERE event_type = 'activity'
    AND event_name IN ('navigation_click', 'ui_click', 'control_changed', 'form_submitted')
    AND visited_at >= v_period_start
    AND visited_at <= v_now;

  SELECT CASE
    WHEN count(session_id) = 0 THEN NULL::bigint
    ELSE count(DISTINCT session_id)
  END
  INTO v_active_sessions
  FROM public.website_action_events
  WHERE visited_at >= v_period_start
    AND visited_at <= v_now;

  -- Sum active foreground-time segments per session, then average only sessions with valid samples.
  WITH session_durations AS (
    SELECT
      session_id,
      sum(
        CASE
          WHEN (metadata->>'duration_ms') ~ '^[0-9]{1,8}$'
            THEN least((metadata->>'duration_ms')::numeric, 1800000)
          ELSE 0
        END
      ) AS duration_ms
    FROM public.website_action_events
    WHERE event_type = 'activity'
      AND event_name = 'page_engagement_duration'
      AND session_id IS NOT NULL
      AND visited_at >= v_period_start
      AND visited_at <= v_now
    GROUP BY session_id
    HAVING sum(
      CASE
        WHEN (metadata->>'duration_ms') ~ '^[0-9]{1,8}$'
          THEN least((metadata->>'duration_ms')::numeric, 1800000)
        ELSE 0
      END
    ) > 0
  )
  SELECT
    round(avg(duration_ms) / 1000.0)::integer,
    count(*)::bigint
  INTO v_average_session_duration_seconds, v_duration_sample_count
  FROM session_durations;

  -- Group by event plus a short, sanitized UI label so operators can distinguish what was clicked.
  SELECT coalesce(
    jsonb_agg(
      jsonb_build_object(
        'name', event_name,
        'label', coalesce(nullif(target_label, ''), nullif(action_detail, ''), initcap(replace(event_name, '_', ' '))),
        'page', page_path,
        'count', amount
      )
      ORDER BY amount DESC, event_name ASC, page_path ASC, target_label ASC
    ),
    '[]'::jsonb
  )
  INTO v_action_summary
  FROM (
    SELECT
      event_name,
      coalesce(nullif(left(btrim(metadata->>'target_label'), 80), ''), '') AS target_label,
      coalesce(
        nullif(left(btrim(metadata->>'form_name'), 80), ''),
        nullif(left(btrim(metadata->>'target_type'), 24), ''),
        nullif(left(btrim(metadata->>'control_type'), 24), ''),
        nullif(left(btrim(metadata->>'section'), 80), ''),
        ''
      ) AS action_detail,
      regexp_replace(
        regexp_replace(coalesce(nullif(left(btrim(page_url), 120), ''), '/'), '/[0-9a-fA-F-]{20,}', '/:id', 'g'),
        '/[0-9]{3,}', '/:id', 'g'
      ) AS page_path,
      count(*)::bigint AS amount
    FROM public.website_action_events
    WHERE event_type = 'activity'
      AND event_name IS NOT NULL
      AND event_name NOT IN ('page_engagement_duration', 'scroll_depth')
      AND visited_at >= v_period_start
      AND visited_at <= v_now
    GROUP BY
      event_name,
      coalesce(nullif(left(btrim(metadata->>'target_label'), 80), ''), ''),
      coalesce(
        nullif(left(btrim(metadata->>'form_name'), 80), ''),
        nullif(left(btrim(metadata->>'target_type'), 24), ''),
        nullif(left(btrim(metadata->>'control_type'), 24), ''),
        nullif(left(btrim(metadata->>'section'), 80), ''),
        ''
      ),
      regexp_replace(
        regexp_replace(coalesce(nullif(left(btrim(page_url), 120), ''), '/'), '/[0-9a-fA-F-]{20,}', '/:id', 'g'),
        '/[0-9]{3,}', '/:id', 'g'
      )
    ORDER BY amount DESC, event_name ASC
    LIMIT 30
  ) action_rows;

  SELECT coalesce(
    jsonb_agg(
      jsonb_build_object('percent', depth_percent, 'count', amount)
      ORDER BY depth_percent
    ),
    '[]'::jsonb
  )
  INTO v_scroll_depth_summary
  FROM (
    SELECT
      (metadata->>'scroll_depth_percent')::integer AS depth_percent,
      count(*)::bigint AS amount
    FROM public.website_action_events
    WHERE event_type = 'activity'
      AND event_name = 'scroll_depth'
      AND metadata->>'scroll_depth_percent' IN ('25', '50', '75', '100')
      AND visited_at >= v_period_start
      AND visited_at <= v_now
    GROUP BY (metadata->>'scroll_depth_percent')::integer
  ) scroll_rows;

  RETURN jsonb_build_object(
    'schemaVersion', 1,
    'timeframe', v_timeframe,
    'totalActions', v_total_actions,
    'totalInteractions', v_total_interactions,
    'actionSummary', v_action_summary,
    'activeSessions', v_active_sessions,
    'averageSessionDurationSeconds', v_average_session_duration_seconds,
    'durationSampleCount', v_duration_sample_count,
    'scrollDepthSummary', v_scroll_depth_summary,
    'lastUpdated', to_char(v_now AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
  );
END;
$function$;

REVOKE ALL ON FUNCTION public.get_community_pulse_action_stats(text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.get_community_pulse_action_stats(text) TO service_role;

COMMENT ON FUNCTION public.get_community_pulse_action_stats(text) IS
  'Server-only aggregates from website_action_events: product events, UI interactions, scroll depth, sessions, and measured foreground duration. Returns no raw visitor identifiers.';

-- Location aggregates are also derived from the new rolling event stream.
CREATE OR REPLACE FUNCTION public.get_community_pulse_city_stats(
  p_timeframe text DEFAULT '24h'
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_timeframe text := lower(coalesce(p_timeframe, '24h'));
  v_now timestamptz := now();
  v_period_start timestamptz;
  v_top_cities jsonb := '[]'::jsonb;
  v_top_city_24h jsonb := NULL;
BEGIN
  IF v_timeframe NOT IN ('24h', '7d', '30d') THEN
    v_timeframe := '24h';
  END IF;

  v_period_start := v_now - CASE v_timeframe
    WHEN '7d' THEN interval '7 days'
    WHEN '30d' THEN interval '30 days'
    ELSE interval '24 hours'
  END;

  SELECT coalesce(
    jsonb_agg(
      jsonb_build_object('name', city_label, 'count', visit_count)
      ORDER BY visit_count DESC, city_label ASC
    ),
    '[]'::jsonb
  )
  INTO v_top_cities
  FROM (
    SELECT
      CASE
        WHEN nullif(trim(region), '') IS NOT NULL
          AND trim(region) <> 'Unknown'
        THEN trim(city) || ', ' || trim(region)
        ELSE trim(city)
      END AS city_label,
      count(*)::bigint AS visit_count
    FROM public.website_action_events
    WHERE event_type = 'pageview'
      AND visited_at >= v_period_start
      AND visited_at <= v_now
      AND nullif(trim(city), '') IS NOT NULL
      AND trim(city) <> 'Unknown'
    GROUP BY 1
    ORDER BY visit_count DESC, city_label ASC
    LIMIT 10
  ) city_rows;

  SELECT jsonb_build_object('name', city_label, 'count', visit_count)
  INTO v_top_city_24h
  FROM (
    SELECT
      CASE
        WHEN nullif(trim(region), '') IS NOT NULL
          AND trim(region) <> 'Unknown'
        THEN trim(city) || ', ' || trim(region)
        ELSE trim(city)
      END AS city_label,
      count(*)::bigint AS visit_count
    FROM public.website_action_events
    WHERE event_type = 'pageview'
      AND visited_at >= v_now - interval '24 hours'
      AND visited_at <= v_now
      AND nullif(trim(city), '') IS NOT NULL
      AND trim(city) <> 'Unknown'
    GROUP BY 1
    ORDER BY visit_count DESC, city_label ASC
    LIMIT 1
  ) city_24h_rows;

  RETURN jsonb_build_object(
    'timeframe', v_timeframe,
    'topCities', v_top_cities,
    'mostVisitedCity24h', v_top_city_24h,
    'lastUpdated', to_char(v_now AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
  );
END;
$$;

-- Recent visitor/action details are admin-only and read from the new event table. No raw IP is stored in it.
CREATE OR REPLACE FUNCTION public.get_admin_recent_visits(
  p_limit int DEFAULT 100,
  p_search text DEFAULT NULL
)
RETURNS TABLE (
  id bigint,
  visited_at timestamptz,
  ip_address text,
  country_code text,
  city text,
  region text,
  page_url text,
  browser text,
  browser_version text,
  os text,
  device_type text,
  device_model text,
  referrer text,
  screen_resolution text,
  language text,
  visitor_id uuid,
  session_id uuid,
  user_id uuid
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $function$
DECLARE
  v_search text := nullif(left(btrim(p_search), 200), '');
  v_limit integer := least(greatest(coalesce(p_limit, 100), 1), 200);
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Unauthorized: Only administrators can view visitor analytics.';
  END IF;

  RETURN QUERY
  SELECT
    v.id,
    v.visited_at,
    NULL::text AS ip_address,
    v.country_code,
    v.city,
    v.region,
    v.page_url,
    v.browser,
    v.browser_version,
    v.os,
    v.device_type,
    v.device_model,
    v.referrer,
    v.screen_resolution,
    v.language,
    v.visitor_id,
    v.session_id,
    v.user_id
  FROM public.website_action_events v
  WHERE v.event_type = 'pageview'
    AND (
      v_search IS NULL
      OR coalesce(v.city, '') ILIKE '%' || v_search || '%'
      OR coalesce(v.country_code, '') ILIKE '%' || v_search || '%'
      OR coalesce(v.page_url, '') ILIKE '%' || v_search || '%'
      OR coalesce(v.referrer, '') ILIKE '%' || v_search || '%'
      OR coalesce(v.visitor_id::text, '') ILIKE '%' || v_search || '%'
    )
  ORDER BY v.visited_at DESC
  LIMIT v_limit;
END;
$function$;

REVOKE ALL ON FUNCTION public.get_admin_recent_visits(int, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.get_admin_recent_visits(int, text) TO authenticated, service_role;

CREATE OR REPLACE FUNCTION public.get_admin_recent_actions(
  p_limit int DEFAULT 50,
  p_timeframe text DEFAULT '24h'
)
RETURNS TABLE (
  id bigint,
  visited_at timestamptz,
  event_name text,
  page_url text,
  visitor_id uuid,
  session_id uuid,
  user_id uuid,
  metadata jsonb
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $function$
DECLARE
  v_timeframe text := lower(coalesce(p_timeframe, '24h'));
  v_period_start timestamptz;
  v_limit integer := least(greatest(coalesce(p_limit, 50), 1), 100);
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Unauthorized: Only administrators can view action analytics.';
  END IF;

  IF v_timeframe NOT IN ('24h', '7d', '30d') THEN
    v_timeframe := '24h';
  END IF;

  v_period_start := now() - CASE v_timeframe
    WHEN '7d' THEN interval '7 days'
    WHEN '30d' THEN interval '30 days'
    ELSE interval '24 hours'
