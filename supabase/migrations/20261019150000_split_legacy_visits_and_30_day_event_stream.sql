  RETURN QUERY
  SELECT
    v.id,
    v.visited_at,
    v.event_name,
    v.page_url,
    v.visitor_id,
    v.session_id,
    v.user_id,
    coalesce(v.metadata, '{}'::jsonb) AS metadata
  FROM public.website_action_events v
  WHERE v.event_type = 'activity'
